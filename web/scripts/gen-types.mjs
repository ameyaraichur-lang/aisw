// Generates TypeScript types from the backend's exported JSON Schemas (source of truth).
// Usage: node scripts/gen-types.mjs [--check]
import { compile } from 'json-schema-to-typescript'
import { readdir, readFile, writeFile } from 'node:fs/promises'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const schemaDir = join(here, '..', '..', 'schemas')
const out = join(here, '..', 'src', 'api', 'contracts.d.ts')
const names = (await readdir(schemaDir)).filter((n) => n.endsWith('.schema.json')).sort()
const seen = new Set()
let text = '// GENERATED by scripts/gen-types.mjs from /schemas - do not edit.\n\n'
for (const n of names) {
  const schema = JSON.parse(await readFile(join(schemaDir, n), 'utf8'))
  const code = await compile(schema, schema.title ?? n, { bannerComment: '', additionalProperties: false, strictIndexSignatures: true })
  // Shared sub-schemas are emitted by every schema that references them: keep the first declaration of each name.
  for (const block of code.split(/\n(?=(?:\/\*\*[\s\S]*?\*\/\n)?export (?:type|interface) )/)) {
    const m = block.match(/export (?:type|interface) (\w+)/)
    if (!m || seen.has(m[1])) continue
    seen.add(m[1])
    text += block.trim() + '\n\n'
  }
}
if (process.argv.includes('--check')) {
  const current = await readFile(out, 'utf8').catch(() => '')
  if (current !== text) { console.error('contracts.d.ts is out of date: run npm run gen:types'); process.exit(1) }
} else {
  await writeFile(out, text)
}
