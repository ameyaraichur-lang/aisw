import { expect, test } from '@playwright/test'
import { approvedManifest, launch, seedProject, signIn, signOut, untilState } from './helpers.ts'

test('a project admin grants a project-only role; the member sees that project and nothing else; revoking ends it', async ({ page, request }) => {
  const mine = await seedProject(request)
  const other = await seedProject(request)
  const runMine = await launch(request, mine.projectId, await approvedManifest(request, mine.projectId))
  const runOther = await launch(request, other.projectId, await approvedManifest(request, other.projectId))
  await untilState(request, runMine, ['REPORT_READY', 'PARTIAL'])

  await signIn(page, 'alice')
  await page.getByRole('navigation').getByRole('link', { name: 'Projects & Environments' }).click()
  await page.getByRole('row').filter({ hasText: mine.name }).getByRole('button', { name: 'Inventory and roles' }).click()
  const panel = page.getByRole('region', { name: 'Project roles' })
  await expect(panel.getByText('No project-only roles.')).toBeVisible()
  await panel.getByLabel('Person (user id)').fill('alice')
  await panel.getByLabel('Reason').fill('self')
  await panel.getByRole('button', { name: 'Grant role' }).click()
  await expect(panel.getByRole('alert')).toContainText('yourself')
  await panel.getByLabel('Person (user id)').fill('pete')
  await panel.getByLabel('Role', { exact: true }).selectOption('report_reader')
  await panel.getByLabel('Reason').fill('external auditor, engagement 12')
  await panel.getByRole('button', { name: 'Grant role' }).click()
  await expect(panel.getByTestId('project-roles').getByRole('row').filter({ hasText: 'pete' })).toContainText('report_reader')
  await signOut(page)

  await signIn(page, 'pete')
  await page.goto('/projects')
  await expect(page.getByRole('table', { name: 'Projects you hold a role on' })).toBeVisible()
  await expect(page.getByRole('row').filter({ hasText: mine.name })).toHaveCount(1)
  await expect(page.getByRole('row').filter({ hasText: other.name })).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Create project' })).toHaveCount(0)
  await page.goto(`/assessments/${runMine}/findings`)
  await expect(page.getByRole('link', { name: /Direct root login/ }).first()).toBeVisible()
  await page.goto(`/assessments/${runOther}/findings`)
  await expect(page.getByRole('link', { name: /Direct root login/ })).toHaveCount(0)
  await expect(page.getByRole('alert').filter({ hasText: 'Access denied' }).first()).toBeVisible()
  await signOut(page)

  await signIn(page, 'alice')
  await page.goto('/projects')
  await page.getByRole('row').filter({ hasText: mine.name }).getByRole('button', { name: 'Inventory and roles' }).click()
  await page.getByRole('region', { name: 'Project roles' }).getByRole('button', { name: 'Revoke' }).click()
  await expect(page.getByRole('region', { name: 'Project roles' }).getByText('No project-only roles.')).toBeVisible()
  await signOut(page)

  await signIn(page, 'pete')
  await page.goto(`/assessments/${runMine}/findings`)
  await expect(page.getByRole('link', { name: /Direct root login/ })).toHaveCount(0)
})
